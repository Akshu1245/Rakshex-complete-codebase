import type { RepairReport } from "./pipeline.js";

const row = (r: RepairReport) => (a: RepairReport["assessments"][number]) =>
  `| \`${a.id}\` | ${a.impact.site.sdkMethod ?? a.impact.site.call} | \`${a.impact.change.property}\` | ${a.level} | ${a.autoApprovable ? "auto (low risk)" : r.approvedSites.includes(a.id) ? "human-approved (signed receipt verified)" : "**STOPPED: human review**"} |`;
const sites = (r: RepairReport) => ["| Site | Call | Property | Risk | Decision |", "|---|---|---|---|---|", ...r.assessments.map(row(r))].join("\n");
const checks = (r: RepairReport) => ["| Check | Status | Detail |", "|---|---|---|", ...r.checks.map((c) => `| ${c.name} | ${c.status === "passed" ? "PASS" : c.status === "failed" ? "FAIL" : "NOT RUN"} | ${c.reason} |`)].join("\n");
const reasons = (r: RepairReport) => r.assessments.map((a) => `- \`${a.id}\`\n${(a.reasons.length ? a.reasons : ["mechanical rename covered by a documented rule"]).map((x) => `  - ${x}`).join("\n")}`).join("\n");

export function renderPrBody(r: RepairReport): string {
  const srcs = [...new Set(r.assessments.map((a) => a.rule?.source).filter(Boolean))];
  return `# [DRAFT] ${r.title}

> Generated by the RaksHex Self-Repair pipeline (deterministic codemod, no AI model). **Draft only.** A human must review and merge.

## Upstream change
${srcs.map((s) => `- ${s}`).join("\n")}

## Affected code
${sites(r)}

## Patch
Bounded key rename at the sites above only. patch sha256: \`${r.patchSha256}\`

## Checks run / not run
${checks(r)}

## Risks
${reasons(r)}
${r.receipt ? `\n## Approval\nSigned receipt ${r.receipt.verified ? "VERIFIED" : "NOT verified"} (signature + patch/impact/checks hashes). Approver: ${r.receipt.approver}.\n` : ""}
## Rollback
Revert this commit.
`;
}

export function renderReview(r: RepairReport): string {
  return `# ${r.status}: ${r.title}

No patch was committed and no PR was opened.

${sites(r)}

## Why
${reasons(r)}
${r.problems.length ? "\n## Problems\n" + r.problems.map((p) => `- ${p}`).join("\n") : ""}

## Checks
${checks(r)}
`;
}

'use client';

import { useMemo, useState } from 'react';

type Finding = { classification?: string; status?: string; confidence?: string; file?: string; file_path?: string; path?: string; reason?: string; line?: number };
type Report = { findings?: Finding[]; results?: Finding[]; impacted_calls?: Finding[]; event?: unknown; change_event?: unknown; summary?: Record<string, unknown>; privacy_mode?: boolean };
const MAX_BYTES = 512 * 1024;

function normalize(json: unknown): Finding[] {
  if (!json || typeof json !== 'object' || Array.isArray(json)) throw new Error('Expected a JSON report object');
  const report = json as Report;
  const raw = report.findings ?? report.results ?? report.impacted_calls;
  if (!Array.isArray(raw)) throw new Error('Report must include findings, results or impacted_calls as an array');
  if (raw.length > 2000) throw new Error('Too many findings (maximum 2000)');
  return raw.map((v) => {
    if (!v || typeof v !== 'object' || Array.isArray(v)) throw new Error('Invalid finding entry');
    const f = v as Finding;
    return { classification: String(f.classification ?? f.status ?? 'UNKNOWN').toUpperCase(), confidence: f.confidence ? String(f.confidence) : undefined };
  });
}

export default function ImpactReviewPanel() {
  const [findings, setFindings] = useState<Finding[] | null>(null);
  const [error, setError] = useState('');
  const counts = useMemo(() => ({
    affected: findings?.filter((f) => f.classification === 'AFFECTED').length ?? 0,
    uncertain: findings?.filter((f) => ['UNCERTAIN','UNKNOWN','REVIEW_REQUIRED'].includes(f.classification ?? '')).length ?? 0,
    other: findings?.filter((f) => !['AFFECTED','UNCERTAIN','UNKNOWN','REVIEW_REQUIRED'].includes(f.classification ?? '')).length ?? 0,
  }), [findings]);

  async function loadFile(file?: File) {
    setError('');
    setFindings(null);
    if (!file) return;
    if (file.size > MAX_BYTES) { setError('File exceeds 512 KB. Export a smaller privacy-safe report.'); return; }
    try {
      const text = await file.text();
      const parsed = JSON.parse(text);
      setFindings(normalize(parsed));
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Cannot read report');
    }
  }

  return (
    <section aria-labelledby="impact-review-heading" className="rounded-xl border border-zinc-800 bg-zinc-900/60 p-5 space-y-4">
      <div className="flex flex-wrap justify-between gap-3 items-start">
        <div>
          <h2 id="impact-review-heading" className="text-lg font-semibold text-zinc-100">API change impact review</h2>
          <p className="text-sm text-zinc-400 mt-1">P1 detection → P2 call-site impact · local report preview</p>
        </div>
        <span className="rounded-full border border-amber-700/60 px-3 py-1 text-xs text-amber-300">Manual import · not live</span>
      </div>
      <p className="text-sm text-zinc-400">Load a <strong>privacy-sanitised</strong> JSON impact report generated by the local scanner. The file is processed in your browser; this panel does not send it to an API. Do not select raw source-code reports.</p>
      <label className="block text-sm text-zinc-200" htmlFor="rakshex-impact-upload">Import sanitised JSON report</label>
      <input id="rakshex-impact-upload" data-testid="impact-report-upload" type="file" accept=".json,application/json" onChange={(e) => void loadFile(e.target.files?.[0])} className="block w-full text-sm text-zinc-300 file:mr-3 file:rounded-md file:border-0 file:bg-zinc-700 file:px-3 file:py-2 file:text-zinc-100" />
      {error && <p role="alert" className="text-sm text-red-300">{error}</p>}
      {!findings ? (
        <div className="rounded-lg border border-dashed border-zinc-700 p-5 text-sm text-zinc-400">No report loaded. No live API changes or customer repositories are connected to this panel.</div>
      ) : (
        <div aria-live="polite" className="space-y-3">
          <div className="grid grid-cols-3 gap-2 text-center">
            <div className="rounded-lg bg-zinc-800 p-3"><div className="text-2xl font-semibold text-red-300">{counts.affected}</div><div className="text-xs text-zinc-400">Affected</div></div>
            <div className="rounded-lg bg-zinc-800 p-3"><div className="text-2xl font-semibold text-amber-300">{counts.uncertain}</div><div className="text-xs text-zinc-400">Needs review</div></div>
            <div className="rounded-lg bg-zinc-800 p-3"><div className="text-2xl font-semibold text-zinc-200">{counts.other}</div><div className="text-xs text-zinc-400">Other</div></div>
          </div>
          <p className="text-xs text-zinc-400">These counts reflect the imported report, not verified accuracy. Paths and source snippets are deliberately not displayed.</p>
          <button type="button" onClick={() => { setFindings(null); setError(''); }} className="rounded-md border border-zinc-700 px-3 py-2 text-sm text-zinc-200 hover:bg-zinc-800">Clear local report</button>
        </div>
      )}
      <p className="text-xs text-zinc-500">No repair, write access, automatic PR, or deployment is enabled by this view.</p>
    </section>
  );
}
